"""Retry tickets: the Idempotency-Key header (PRD section 5, CLAUDE.md rule 5).

A phone on a bad connection may send the same change twice. The app attaches a random UUID
(the key) to every change. The first request with a key runs normally and its response is
saved for 24 hours. A retry with the same key gets the saved response back, marked
`Idempotent-Replayed: true`, and the work is NOT done again.

Rules (Stripe / IETF conventions):
- Required on every POST, PUT, PATCH and DELETE under /v1, except the sign-in routes
  (/v1/auth/*) and the pure calculation POST /v1/split/preview.
- Keys are scoped per user.
- Same key, different request body: 422. Same key while the first is still running: 409.
- Server errors (5xx) and crashes are not saved, so a retry runs again. That's safe because
  the failed request's database transaction was rolled back.
"""

import hashlib
import json
import uuid
from datetime import UTC, datetime, timedelta

from fastapi import Header
from sqlalchemy import delete, update
from sqlalchemy.dialects.postgresql import insert
from sqlalchemy.ext.asyncio import AsyncSession, async_sessionmaker
from starlette.middleware.base import BaseHTTPMiddleware, RequestResponseEndpoint
from starlette.requests import Request
from starlette.responses import Response

from app.core.errors import problem_response
from app.models import IdempotencyKey
from app.services.auth.tokens import InvalidToken, decode_access_token

HEADER = "Idempotency-Key"
TTL = timedelta(hours=24)
WRITE_METHODS = {"POST", "PUT", "PATCH", "DELETE"}
EXEMPT_PREFIXES = ("/v1/auth/",)
EXEMPT_PATHS = {"/v1/split/preview"}


def needs_key(method: str, path: str) -> bool:
    return (
        method in WRITE_METHODS
        and path.startswith("/v1/")
        and not path.startswith(EXEMPT_PREFIXES)
        and path not in EXEMPT_PATHS
    )


def idempotency_key_header(
    idempotency_key: uuid.UUID = Header(  # noqa: B008 - FastAPI's way of declaring a header
        alias=HEADER,
        description="A UUID generated by the app for this change. Retries reuse it.",
    ),
) -> uuid.UUID:
    """Declared on write routes so the header appears in the OpenAPI contract (and the
    generated Swift client). The middleware below does the actual work."""
    return idempotency_key


class IdempotencyMiddleware(BaseHTTPMiddleware):
    async def dispatch(self, request: Request, call_next: RequestResponseEndpoint) -> Response:
        if not needs_key(request.method, request.url.path):
            return await call_next(request)

        user_id = self._user_id(request)
        if user_id is None:
            return await call_next(request)  # not signed in: the route answers 401

        raw_key = request.headers.get(HEADER)
        if raw_key is None:
            return problem_response(
                400,
                "idempotency-key-required",
                detail=f"Changes must include an {HEADER} header (a UUID).",
            )
        try:
            key = uuid.UUID(raw_key)
        except ValueError:
            return problem_response(
                400, "invalid-idempotency-key", detail=f"{HEADER} must be a UUID."
            )

        body = await request.body()
        target = request.url.path + (f"?{request.url.query}" if request.url.query else "")
        request_hash = hashlib.sha256(
            request.method.encode() + b"\n" + target.encode() + b"\n" + body
        ).hexdigest()

        sessionmaker = request.app.state.sessionmaker
        now = datetime.now(UTC)
        claimed = await self._claim(sessionmaker, user_id, key, request, target, request_hash, now)
        if not claimed:
            async with sessionmaker() as session:
                row = await session.get(IdempotencyKey, (user_id, key))
            if row is None:
                # The other request failed and released the key a moment ago; try once more.
                if not await self._claim(
                    sessionmaker, user_id, key, request, target, request_hash, now
                ):
                    return _in_progress()
            elif row.request_hash != request_hash:
                return problem_response(
                    422,
                    "idempotency-key-reused",
                    detail="This Idempotency-Key was already used for a different request.",
                )
            elif row.response_status is None:
                return _in_progress()
            else:
                return _replay(row)

        try:
            response = await call_next(request)
        except Exception:
            await self._release(sessionmaker, user_id, key)
            raise

        content = b"".join([chunk async for chunk in response.body_iterator])  # type: ignore[attr-defined]
        if response.status_code >= 500:
            await self._release(sessionmaker, user_id, key)
        else:
            async with sessionmaker() as session:
                await session.execute(
                    update(IdempotencyKey)
                    .where(IdempotencyKey.user_id == user_id, IdempotencyKey.key == key)
                    .values(
                        response_status=response.status_code,
                        response_json=json.loads(content) if content else None,
                    )
                )
                await session.commit()
        return Response(
            content=content,
            status_code=response.status_code,
            headers=dict(response.headers),
            media_type=response.media_type,
        )

    @staticmethod
    def _user_id(request: Request) -> uuid.UUID | None:
        auth = request.headers.get("authorization", "")
        scheme, _, token = auth.partition(" ")
        if scheme.lower() != "bearer" or not token:
            return None
        secret = request.app.state.settings.jwt_secret.get_secret_value()
        try:
            return decode_access_token(token, secret).user_id
        except InvalidToken:
            return None

    @staticmethod
    async def _claim(
        sessionmaker: async_sessionmaker[AsyncSession],
        user_id: uuid.UUID,
        key: uuid.UUID,
        request: Request,
        target: str,
        request_hash: str,
        now: datetime,
    ) -> bool:
        """Insert the key as 'in progress'. Returns False if it already exists (and isn't
        expired). The primary key makes this safe when two retries race."""
        async with sessionmaker() as session:
            # An expired key from yesterday can be reused.
            await session.execute(
                delete(IdempotencyKey).where(
                    IdempotencyKey.user_id == user_id,
                    IdempotencyKey.key == key,
                    IdempotencyKey.expires_at <= now,
                )
            )
            result = await session.execute(
                insert(IdempotencyKey)
                .values(
                    user_id=user_id,
                    key=key,
                    method=request.method,
                    path=target[:512],
                    request_hash=request_hash,
                    expires_at=now + TTL,
                )
                .on_conflict_do_nothing()
                .returning(IdempotencyKey.key)
            )
            claimed = result.scalar_one_or_none() is not None
            await session.commit()
            return claimed

    @staticmethod
    async def _release(
        sessionmaker: async_sessionmaker[AsyncSession], user_id: uuid.UUID, key: uuid.UUID
    ) -> None:
        async with sessionmaker() as session:
            await session.execute(
                delete(IdempotencyKey).where(
                    IdempotencyKey.user_id == user_id, IdempotencyKey.key == key
                )
            )
            await session.commit()


def _in_progress() -> Response:
    return problem_response(
        409,
        "request-in-progress",
        detail="The first request with this Idempotency-Key is still running. Retry shortly.",
        headers={"Retry-After": "1"},
    )


def _replay(row: IdempotencyKey) -> Response:
    status = row.response_status or 200
    headers = {"Idempotent-Replayed": "true"}
    if row.response_json is None:
        return Response(status_code=status, headers=headers)
    media = "application/problem+json" if status >= 400 else "application/json"
    return Response(
        content=json.dumps(row.response_json),
        status_code=status,
        headers=headers,
        media_type=media,
    )
